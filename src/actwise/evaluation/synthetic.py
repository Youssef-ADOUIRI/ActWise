"""Draft golden-set candidates with an LLM: questions from dev/test passages, and refusals.

Each candidate is screened by rule here, then reviewed by a person before it joins
data/eval/golden.jsonl.
"""

from __future__ import annotations

import random
import re
from collections import defaultdict
from typing import Any

from actwise.evaluation.golden import NAMES_AN_ARTICLE
from actwise.evaluation.splits import SEED
from actwise.generation.prompts import json_object, load_prompt
from actwise.ids import article_id
from actwise.ingest.chunk import Chunk
from actwise.llm.base import LLM

IN_SCOPE_PROMPT, OUT_OF_SCOPE_PROMPT = "synthetic.v1", "synthetic_oos.v1"
LANGUAGES = {"en": "English", "fr": "French"}
FR_SHARE = 0.3  # the share of French in the hand-written set
IN_SCOPE_TYPES = ("lookup", "definition", "obligation")
MIN_WORDS = 25  # shorter passages rarely support a realistic question
# Clearly outside both laws: nothing about AI systems, personal data or privacy.
OUT_OF_SCOPE_TOPICS = [
    "gatekeeper obligations under the Digital Markets Act",
    "notice-and-action for illegal content under the Digital Services Act",
    "access to data generated by connected products under the Data Act",
    "incident reporting deadlines under the NIS2 Directive",
    "security requirements for products with digital elements under the Cyber Resilience Act",
    "European Digital Identity Wallets under the eIDAS regulation",
    "VAT rules for cross-border e-commerce sales",
    "EU merger control notification thresholds",
    "maximum weekly working time under the Working Time Directive",
    "CE marking of toys under the Toy Safety Regulation",
    "roaming charges inside the EU",
    "accessibility requirements for e-books under the European Accessibility Act",
    "licensing of crypto-asset service providers under MiCA",
    "the battery passport under the Batteries Regulation",
    "due diligence under the EU Deforestation Regulation",
    "reporting under the Carbon Border Adjustment Mechanism",
    "strong customer authentication for online payments under PSD2",
    "allergen labelling on prepacked food",
    "the 14-day right of withdrawal for online purchases",
    "the EU Taxonomy for sustainable activities",
    "the ban on single-use plastic products",
    "passenger compensation for cancelled flights",
    "mutual recognition of professional qualifications in the EU",
    "anti-dumping duties on imported steel",
]


def pick_chunks(
    chunks: list[Chunk], article_split: dict[str, str], split: str, n: int
) -> list[Chunk]:
    """`n` article or annex paragraphs of `split`, spread over as many articles as possible.

    Paragraphs are drawn round-robin over the articles, so every article gets one before
    any gets two; about `FR_SHARE` of them come in their French version.
    """
    rng = random.Random(f"{SEED}-{split}")
    by_article: dict[str, list[str]] = defaultdict(list)
    for c in chunks:
        if (
            c.lang == "en"
            and c.kind != "recital"
            and article_split.get(article_id(c.id)) == split
            and len(c.text.split()) >= MIN_WORDS
        ):
            by_article[article_id(c.id)].append(c.id)
    articles = sorted(by_article)
    rng.shuffle(articles)
    for ids in by_article.values():
        rng.shuffle(ids)
    picked: list[str] = []
    while len(picked) < n and any(by_article.values()):
        for a in articles:
            if by_article[a] and len(picked) < n:
                picked.append(by_article[a].pop())
    by_key = {(c.id, c.lang): c for c in chunks}
    return [
        by_key.get((i, "fr" if rng.random() < FR_SHARE else "en"), by_key[i, "en"]) for i in picked
    ]


def normalise(question: str) -> str:
    """Lowercase letters and digits only: two questions that differ in punctuation match."""
    return " ".join(re.findall(r"\w+", question.lower()))


def screen(candidate: dict[str, Any], seen: set[str]) -> list[str]:
    """Rule-based reasons to drop a candidate; `seen` holds normalised questions so far."""
    question = candidate["question"]
    if not question:
        return ["unreadable reply"]
    reasons = []
    if NAMES_AN_ARTICLE.search(question):
        reasons.append("names its article")
    if normalise(question) in seen:
        reasons.append("duplicate")
    if len(question.split()) < 5:
        reasons.append("too short")
    if candidate["gold"] and candidate["type"] not in IN_SCOPE_TYPES:
        reasons.append(f"unknown type {candidate['type']!r}")
    return reasons


def _draft(llm: LLM, prompt: str, lang: str, body: str) -> dict[str, str]:
    """Ask for one question as JSON; a field the reply lacks comes back empty."""
    messages = [
        {"role": "system", "content": load_prompt(prompt)},
        {"role": "user", "content": f"Language: {LANGUAGES[lang]}\n\n{body}"},
    ]
    data = json_object(llm.chat(messages, temperature=0).text) or {}
    return {field: str(data.get(field, "")).strip() for field in ("question", "reference", "type")}


def draft_in_scope(llm: LLM, chunk: Chunk, split: str) -> dict[str, Any]:
    """A question that `chunk` answers, in the chunk's language; gold is its article."""
    draft = _draft(llm, IN_SCOPE_PROMPT, chunk.lang, f"Passage:\n{chunk.embed_text}")
    return draft | {
        "lang": chunk.lang,
        "gold": [article_id(chunk.id)],
        "split": split,
        "source": chunk.id,
    }


def draft_out_of_scope(llm: LLM, topic: str, lang: str, split: str) -> dict[str, Any]:
    """A question on `topic` that neither the AI Act nor the GDPR answers."""
    draft = _draft(llm, OUT_OF_SCOPE_PROMPT, lang, f"Topic: {topic}")
    return draft | {
        "lang": lang,
        "type": "not_covered",
        "gold": [],
        "split": split,
        "source": topic,
    }
